const APERTURE = LID_EDGE + FLOOR;

/**
 * Веко: тот же край, замкнутый далеко вверх И далеко в стороны.
 *
 * Вверх - потому что веко закрывает глаз сдвигом вниз, и всё, что выше его
 * собственной кромки, осталось бы незакрытым: глаз закрывался бы снизу вверх.
 *
 * В стороны - из-за сглаживания. Прорезь и веко обрезаны одним контуром, и
 * пока боковые края века стояли ровно на краях прорези (104 и 832), на
 * границе складывались две полупрозрачные кромки: под веком просвечивал
 * белок, и по закрытому глазу шла светлая нитка. Веко, уходящее за обрезку,
 * кроет свой край целиком, и полупрозрачная кромка остаётся ровно одна - у
 * самой обрезки.
 *
 * Кожа кончается РОВНО на линии ресниц, и это выбор владельца. Пробовали
 * иначе: кожа продолжалась на 120 единиц ниже, ресница садилась в середину
 * прорези, а под ней оставалась кожа - «одна линия по коже», как рисуют
 * закрытый глаз. Отвергнуто, прежний вариант оказался лучше. Не возвращать
 * без спроса.
 */
const LID = `M-260 662.6L${LID_EDGE_POINTS}L1980 612.7L1980 -400L-260 -400Z`;

const PUPIL = { cx: 537.4, cy: 692, r: 92 };

/** Краска логотипа, не палитра темы: это рисунок марки, а не элемент интерфейса. */
const SCLERA = "#f8f8f8";
const INK = "#251f1e";
/** Веко - это кожа, поэтому оно цвета лица, а не цвета контура. */
const SKIN = "#709080";

/**
 * Подписка на взгляд.
 *
 * `active` выключает её целиком: пока защита стоит, глаз закрыт, и держать
 * ради него слушателей движения и кадровый цикл незачем.
 */
export function useGaze(active: boolean): Gaze {
  const [gaze, setGaze] = useState<Gaze>(CENTRED);

  useEffect(() => {
    if (!active || motionIsUnwelcome()) {
      setGaze(CENTRED);
      return undefined;
    }
    return gazeSource.subscribe(setGaze);
  }, [active]);

  return active ? gaze : CENTRED;
}

export default function Eye({ gaze, closed }: { gaze: Gaze; closed: boolean }) {
  // `useId` вместо строкового имени: два таких слоя на одной странице
  // столкнулись бы идентификаторами обрезки, и один остался бы без неё.
  const clip = useId();

  const dx = gaze.x * GAZE_RANGE.x;
  const dy = gaze.y * GAZE_RANGE.y;

  return (
    <svg
      className="eye-svg"
      viewBox="0 0 1720 1804"
      data-closed={closed}
      aria-hidden="true"
      focusable="false"
    >
      <defs>
        <clipPath id={clip}>
          <path d={APERTURE} />
        </clipPath>
      </defs>
      <g clipPath={`url(#${clip})`}>
        <path d={APERTURE} fill={SCLERA} />
        <circle cx={PUPIL.cx + dx} cy={PUPIL.cy + dy} r={PUPIL.r} fill={INK} />
        {/* Веко едет по тому же краю, которым обрезана прорезь, поэтому
            закрывается глаз своей же линией, а не прямой шторкой. */}
        <g className="eye-lid">
          <path d={LID} fill={SKIN} />
          {/* Ресница идёт по тому же краю, которым обрезана прорезь, - глаз
              закрывается своей же линией, а не прямой шторкой. */}
          <path
            d={LID_EDGE}
            fill="none"
            stroke={INK}
            strokeWidth={26}
            strokeLinejoin="round"
            strokeLinecap="round"
          />
        </g>
      </g>
    </svg>
  );
}
