// src/components/Eye.tsx
//
// Живой глаз марки: следит, пока защита выключена, и закрывается, когда она
// встала, - вместе с замком. Закрытый глаз и есть обещание сервиса: пока
// туннель поднят, мы не смотрим.
//
// Марка не переделана. Слой рисует поверх неё весь разрез глаза заново -
// белок по прорези, зрачок, сверху веко, - и то, что нарисовано в самой
// марке, оказывается закрыто. Отсюда важное свойство: если слой почему-то не
// отрисуется, под ним останется исходный глаз, а не дырка.
//
// Геометрия снята с самой марки:
//
//   прорезь   нижний край века и нижнее веко, снятые по столбцам; там, где
//             веко закрыто радужкой (263 единицы), край интерполирован -
//             ошибка в пару единиц на холсте 1720 при выводе в 104 px меньше
//             десятой доли пикселя
//   зрачок    круг радиусом 92 на высоте 692
//
// Почему зрачок меньше радужки из марки. В марке радужка выше самой прорези
// (266 против 233 в самом широком месте) и всегда срезана веком - как у живого
// глаза, но читается она при этом сплошной массой, а не кругом. Стоило ей
// поехать за наклоном, и круга не получалось.
//
// Размер выбран из прорези: по центральному столбцу она 233 единицы (580 -
// 813), значит на зрачок и на просвет сверху и снизу остаётся 233 - 2*ход.
// При радиусе 92 и высоте 692 на краю хода сверху остаётся 10 единиц белка,
// снизу 19 - зрачок не срастается ни с веком, ни с нижним краем. 84 уже
// выглядит мультяшным, 133 - это исходное пятно из марки.

import { useEffect, useId, useState } from "react";

import { CENTRED, GAZE_RANGE, gazeSource, motionIsUnwelcome, type Gaze } from "../gaze";

/** Нижний край верхнего века - он же верхняя граница прорези. */
const LID_EDGE =
  "M104 663L117 659L135 648L198 624L219 620L225 616L231 616L251 608L274 604L281 600" +
  "L287 600L295 596L305 596L314 592L331 591L336 588L352 588L361 584L383 584L392 580" +
  "L677 580L686 584L705 584L712 588L727 588L736 592L748 592L755 596L767 596L774 600" +
  "L784 600L788 603L799 604L806 608L816 608L832 614";

/** Нижнее веко, обратным ходом: вместе с краем века замыкает прорезь. */
const FLOOR =
  "L832 615L811 641L752 700L707 733L702 739L695 741L690 746L631 780L609 788L577 804" +
  "L570 804L553 812L545 812L514 824L505 824L498 828L484 828L476 832L466 832L459 836" +
  "L442 836L434 840L409 840L401 844L295 847L289 844L252 844L244 840L201 836L195 832" +
  "L182 832L176 828L150 824L145 820L133 820L128 816L121 816L104 809Z";

const APERTURE = LID_EDGE + FLOOR;

/**
 * Само веко: тот же край, замкнутый далеко вверх.
 *
 * Уходить вверх надо именно далеко. Веко закрывает глаз сдвигом вниз на 270,
 * и всё, что выше его собственной верхней кромки, останется незакрытым: с
 * кромкой на 420 сдвинутое веко начиналось бы с 690 и накрывало бы прорезь
 * снизу, а не сверху - глаз закрывался бы наоборот. Кромка на -400 после
 * сдвига всё ещё выше прорези, и веко идёт сверху вниз, как ему и положено.
 */
const LID = `${LID_EDGE}L832 -400L104 -400Z`;

const PUPIL = { cx: 537.4, cy: 692, r: 92 };

/** Краска логотипа, не палитра темы: это рисунок марки, а не элемент интерфейса. */
const SCLERA = "#f8f8f8";
const INK = "#251f1e";
/** Веко - это кожа, поэтому оно цвета лица, а не цвета контура. */
const SKIN = "#709080";

/**
 * Подписка на взгляд.
 *
 * `active` выключает её целиком: пока защита стоит, глаз закрыт, и держать
 * ради него слушателей движения и кадровый цикл незачем.
 */
export function useGaze(active: boolean): Gaze {
  const [gaze, setGaze] = useState<Gaze>(CENTRED);

  useEffect(() => {
    if (!active || motionIsUnwelcome()) {
      setGaze(CENTRED);
      return undefined;
    }
    return gazeSource.subscribe(setGaze);
  }, [active]);

  return active ? gaze : CENTRED;
}

export default function Eye({ gaze, closed }: { gaze: Gaze; closed: boolean }) {
  // `useId` вместо строкового имени: два таких слоя на одной странице
  // столкнулись бы идентификаторами обрезки, и один остался бы без неё.
  const clip = useId();

  const dx = gaze.x * GAZE_RANGE.x;
  const dy = gaze.y * GAZE_RANGE.y;

  return (
    <svg
      className="eye-svg"
      viewBox="0 0 1720 1804"
      data-closed={closed}
      aria-hidden="true"
      focusable="false"
    >
      <defs>
        <clipPath id={clip}>
          <path d={APERTURE} />
        </clipPath>
      </defs>
      <g clipPath={`url(#${clip})`}>
        <path d={APERTURE} fill={SCLERA} />
        <circle cx={PUPIL.cx + dx} cy={PUPIL.cy + dy} r={PUPIL.r} fill={INK} />
        {/* Веко едет по тому же краю, которым обрезана прорезь, поэтому
            закрывается глаз своей же линией, а не прямой шторкой. */}
        <g className="eye-lid">
          <path d={LID} fill={SKIN} />
          <path d={LID_EDGE} fill="none" stroke={INK} strokeWidth={26} strokeLinejoin="round" />
        </g>
      </g>
    </svg>
  );
}
