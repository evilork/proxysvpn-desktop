//
// Марка не переделана. Слой рисует поверх неё весь разрез глаза заново -
// белок по прорези, зрачок, сверху веко, - и то, что нарисовано в самой
// марке, оказывается закрыто. Отсюда важное свойство: если слой почему-то не
// отрисуется, под ним останется исходный глаз, а не дырка.
//
// Геометрия снята с самой марки:
//
//   прорезь   нижний край века и нижнее веко, снятые по столбцам с удвоенным
