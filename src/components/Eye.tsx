// Живой глаз марки: зрачок держит взгляд, пока телефон поворачивается.
//
// Марка не переделана. Слой рисует поверх неё весь разрез глаза заново -
// сначала белок по всей прорези, потом радужку на своём месте, - и старая
// радужка оказывается закрыта. Отсюда важное свойство: если этот слой почему-
// то не отрисуется, под ним остаётся исходный глаз, а не дырка.
//
// Геометрия снята с самой марки, не нарисована на глаз:
//
//   радужка   окружность (537.4, 627.1) радиусом 132.9 - подгонка по 350
//             точкам границы, средняя ошибка 0.72 единицы холста, это 0.04
//             экранного пикселя при нынешнем размере эмблемы
//   прорезь    нижний край века и нижнее веко, снятые по столбцам; там, где
//             веко закрыто радужкой (263 единицы), край интерполирован -
//             ошибка в пару единиц на холсте 1720 при выводе в 104 px
//             меньше десятой доли пикселя
//
// Ход зрачка ограничен тем, что под радужкой остаётся всего 56 единиц белка:
// вниз больше 16 - и глаз упрётся в нижнее веко.

import { useEffect, useId, useState } from "react";

import { CENTRED, GAZE_RANGE, gazeSource, motionIsUnwelcome, type Gaze } from "../gaze";

/** Контур прорези глаза в единицах холста марки. */
const APERTURE =
  "M104 663L117 659L135 648L198 624L219 620L225 616L231 616L251 608L274 604L281 600" +
  "L287 600L295 596L305 596L314 592L331 591L336 588L352 588L361 584L383 584L392 580" +
  "L677 580L686 584L705 584L712 588L727 588L736 592L748 592L755 596L767 596L774 600" +
  "L784 600L788 603L799 604L806 608L816 608L832 614L832 615L811 641L752 700L707 733" +
  "L702 739L695 741L690 746L631 780L609 788L577 804L570 804L553 812L545 812L514 824" +
  "L505 824L498 828L484 828L476 832L466 832L459 836L442 836L434 840L409 840L401 844" +
  "L295 847L289 844L252 844L244 840L201 836L195 832L182 832L176 828L150 824L145 820" +
  "L133 820L128 816L121 816L104 809Z";

const IRIS = { cx: 537.4, cy: 627.1, r: 132.9 };

/** Цвета взяты из самой марки, а не из палитры темы: это краска логотипа. */
const SCLERA = "#f8f8f8";
const INK = "#251f1e";

/**
 * Подписка на взгляд.
 *
 * Значение приходит кадрами, поэтому состояние обновляется часто - но только
 * пока зрачок едет: источник сам останавливает цикл, когда доехал.
 */
export function useGaze(): Gaze {
  const [gaze, setGaze] = useState<Gaze>(CENTRED);

  useEffect(() => {
    if (motionIsUnwelcome()) return undefined;
    return gazeSource.subscribe(setGaze);
  }, []);

  return gaze;
}

export default function Eye({ gaze }: { gaze: Gaze }) {
  // `useId` вместо строкового имени: два таких слоя на одной странице
  // столкнулись бы идентификаторами обрезки, и один остался бы без неё.
  const clip = useId();

  const dx = gaze.x * GAZE_RANGE.x;
  const dy = gaze.y * GAZE_RANGE.y;

  return (
    <svg
      className="eye-svg"
      viewBox="0 0 1720 1804"
      aria-hidden="true"
      focusable="false"
    >
      <defs>
        <clipPath id={clip}>
          <path d={APERTURE} />
        </clipPath>
      </defs>
      <g clipPath={`url(#${clip})`}>
        <path d={APERTURE} fill={SCLERA} />
        <circle cx={IRIS.cx + dx} cy={IRIS.cy + dy} r={IRIS.r} fill={INK} />
      </g>
    </svg>
  );
}
